"""Generate the commentable architecture document from the README's graph source."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "docs/review/sudograph-architecture.md"
REPOSITORY = "https://github.com/sudoprivacy/sudograph"
START = "<!-- architecture-discussion:start -->"
END = "<!-- architecture-discussion:end -->"
NODE = re.compile(r'^\s*([A-Z][A-Z0-9_]*)\s*(?:\[\("(.*?)"\)\]|\["(.*?)"\])\s*$')
EDGE = re.compile(r'^\s*([A-Z][A-Z0-9_]*)\s*(-->|-\.->)(?:\|([^|]+)\|)?\s*([A-Z][A-Z0-9_]*)\s*$')


def review_document(readme: str) -> str:
    """Copy the section exactly; derive its commentable inventories, never a second graph."""
    parts = readme.split("## Where this sits\n")
    if len(parts) != 2:
        raise ValueError("README must contain exactly one architecture section")
    section = parts[1].split("\n## ", 1)[0].strip()
    if START in section or END in section:
        if section.count(START) != 1 or section.count(END) != 1:
            raise ValueError("architecture discussion markers must be paired")
        if section.index(START) > section.index(END):
            raise ValueError("architecture discussion markers are out of order")
        section = re.sub(re.escape(START) + r".*?" + re.escape(END), "", section, flags=re.S)
        section = section.strip()
    diagrams = re.findall(r"```mermaid\n(.*?)\n```", section, re.S)
    if len(diagrams) != 1:
        raise ValueError("architecture review requires exactly one source diagram")
    diagram = diagrams[0]
    nodes, edges = {}, []
    for line in diagram.splitlines():
        if match := NODE.fullmatch(line):
            identity, box, cylinder = match.groups()
            if identity in nodes:
                raise ValueError(f"duplicate architecture identity: {identity}")
            nodes[identity] = box or cylinder
        elif match := EDGE.fullmatch(line):
            edges.append(match.groups())
        elif "-->" in line or "-.->" in line:
            raise ValueError(
                "unsupported relationship syntax; update the checked document exporter"
            )
        elif re.match(r"\s*[A-Z][A-Z0-9_]*\s*[\[({]", line):
            raise ValueError("unsupported node syntax; update the checked document exporter")
    if not nodes or not edges or any(a not in nodes or b not in nodes for a, _, _, b in edges):
        raise ValueError("architecture graph has no inventory or an unknown relationship endpoint")
    # Relative README links become absolute; graph text and source labels stay intact.
    section = re.sub(
        r"\]\(((?:docs|infra|examples)/[^)]+)\)",
        lambda match: "](" + REPOSITORY + "/blob/main/" + match[1] + ")",
        section,
    )
    fingerprint = hashlib.sha256(diagram.encode()).hexdigest()
    node_rows = [
        f"| `{identity}` | {label.replace('<br/>', ' / ')} |"
        for identity, label in nodes.items()
    ]
    edge_rows = [
        f"| `{a}` | `{b}` | {'Planned connection' if arrow == '-.->' else 'Current path'} "
        f"| {label or 'Unlabelled in the source diagram'} |"
        for a, arrow, label, b in edges
    ]
    return (
        "# Sudograph architecture review\n\n"
        "<!-- Generated by python -m tools.architecture_review; "
        "edit README.md, not this file. -->\n\n"
        "This is the commentable counterpart of the "
        f"[README architecture]({REPOSITORY}#where-this-sits). "
        "The diagram, labels and boundaries come from that single source. "
        "Select readable text in the node and relationship inventories below "
        "to comment on a specific responsibility or connection. "
        "The README discussion link is temporary and will be removed after design alignment.\n\n"
        f"Diagram source SHA-256: `{fingerprint}`.\n\n"
        "**Markdown viewer issue:** region comments on Mermaid nodes currently lose "
        "their element location after reload. Prefer text comments on the inventories "
        "while the [ShareOne BR/FR]"
        f"({REPOSITORY}/blob/main/docs/shareone-markdown-mermaid-comments-br-2026-10-13.md) "
        "is pending. The complete diagram remains the visual reference.\n\n"
        "## Architecture\n\n" + section + "\n\n"
        "## Node inventory for precise comments\n\n"
        "Identifiers below are the node names in the Mermaid source. "
        "Labels, layout and a display-language change do not allocate new node identities.\n\n"
        "| Source node ID | Exact source label |\n| --- | --- |\n"
        + "\n".join(node_rows) + "\n\n"
        "## Relationship inventory for precise comments\n\n"
        "Every source edge is retained, including separate edges between the same endpoints. "
        "A solid connection describes the architecture's current path; it does not imply "
        "that separate services are connected in the isolated GitLab deployment. "
        "The implementation boundaries above remain authoritative.\n\n"
        "| From | To | Diagram style | Exact source annotation |\n"
        "| --- | --- | --- | --- |\n"
        + "\n".join(edge_rows) + "\n\n"
        "## Hands-on review after architecture alignment\n\n"
        "The previous disposable acceptance stack has been removed. "
        "This discussion page is not a running GitLab workspace or a login screen. "
        "Start a separate installation using the "
        f"[deployment instructions]({REPOSITORY}/blob/main/infra/gitlab/README.md) "
        "before attempting the following review.\n\n"
        "1. An authorised agent reads the registered contract "
        "and submits a model change with intent.\n"
        "2. Inspect the resulting GitLab merge request, exact commit and automatically generated "
        "CI review artifact. Successful CI alone must not publish the proposal.\n"
        "3. As the independent reviewer, inspect the draft "
        "and approve that exact revision in GitLab.\n"
        "4. Confirm the publisher independently checks and compiles it, "
        "merges the reviewed revision "
        "and serves the accepted reader with a verifiable receipt.\n"
        "5. Check that a new commit needs a new review; try a reviewed rollback and verify "
        "that definitions retain their identities.\n\n"
        "The [deployed acceptance record]"
        f"({REPOSITORY}/blob/main/docs/trials/gitlab-managed-2026-10-13.md) "
        "proves the technical path on synthetic data. Human hands-on review is still needed "
        "to establish that the interaction matches the intended workflow.\n"
    )


def check() -> None:
    expected = review_document((ROOT / "README.md").read_text(encoding="utf8"))
    if DOCUMENT.read_text(encoding="utf8") != expected:
        raise ValueError("architecture review drifted; run python -m tools.architecture_review")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="refuse a stale or edited review document"
    )
    args = parser.parse_args()
    if args.check:
        check()
        print("Architecture review matches the README graph and its complete inventories")
    else:
        content = review_document((ROOT / "README.md").read_text(encoding="utf8"))
        DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
        DOCUMENT.write_text(content, encoding="utf8")
        print(DOCUMENT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
